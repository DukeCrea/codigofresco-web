export function formatReviewDate(iso: string, lang: Locale) {
  return new Intl.DateTimeFormat(lang === "es" ? "es-PA" : "en-US", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${iso}T12:00:00Z`));
}
